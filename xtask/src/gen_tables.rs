//! `cargo xtask gen-tables`: regenerates every file derived from the GPUI sources.
//!
//! Outputs (all committed; CI regenerates and runs `git diff --exit-code`):
//! - `crates/gpui-rsx-core/src/codegen/tables_generated.rs` — method facts, camelCase aliases,
//!   and the Tailwind palette lookup.
//! - `tests/fixtures/gpui_api/<Trait>.txt` — API snapshot fixtures (`name/arity`).
//! - `crates/gpui-stub/src/generated.rs` — the GPUI stub used by doctests.
//! - `demo/src/bin/generated_api_contract.rs` — calls every zero-argument method against
//!   real GPUI so a mistake in the generator fails the demo build.
//! - Test and benchmark mock defaults derived from the same API.

use crate::gpui_api::{GpuiApi, Method, Origin, TRAITS};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

pub struct Outputs {
    pub files: Vec<(PathBuf, String)>,
}

pub use crate::upstream::{Revisions, locked_revisions};

/// Reads `ThemeColor` fields from a gpui-component registry package or checkout.
pub fn theme_color_fields(component_ui_root: &Path) -> Result<Vec<String>, String> {
    let path = component_ui_root.join("src/theme/theme_color.rs");
    let source = std::fs::read_to_string(&path)
        .map_err(|e| format!("failed to read {}: {e}", path.display()))?;
    let file =
        syn::parse_file(&source).map_err(|e| format!("failed to parse {}: {e}", path.display()))?;
    file.items
        .iter()
        .find_map(|item| match item {
            syn::Item::Struct(s) if s.ident == "ThemeColor" => Some(
                s.fields
                    .iter()
                    .filter_map(|f| f.ident.as_ref().map(ToString::to_string))
                    .collect::<Vec<_>>(),
            ),
            _ => None,
        })
        .ok_or_else(|| format!("struct ThemeColor not found in {}", path.display()))
}

pub fn generate(
    api: &GpuiApi,
    theme_fields: &[String],
    revs: &Revisions,
    workspace: &Path,
) -> Result<Outputs, String> {
    let palette = load_palette(&workspace.join("xtask/data/tailwind-palette.txt"))?;
    let methods = merged_methods(api);

    let mut tables = core_tables(&methods, &palette, revs);
    let _ = writeln!(
        tables,
        "\n/// `ThemeColor` fields of {}, used by the `gpui-component` theme preset.\npub const GPUI_COMPONENT_THEME_COLORS: &[&str] = &[{}];",
        revs.component,
        theme_fields
            .iter()
            .map(|f| format!("\"{f}\""))
            .collect::<Vec<_>>()
            .join(", ")
    );
    let mut files = vec![(
        workspace.join("crates/gpui-rsx-core/src/codegen/tables_generated.rs"),
        tables,
    )];
    files.push((
        workspace.join("tests/fixtures/gpui_api/TypeContracts.txt"),
        format!(
            "# Explicit signatures and complete style-generation templates at {}\n{}",
            revs.gpui, api.signature_contract
        ),
    ));
    for (trait_name, _) in TRAITS {
        files.push((
            workspace.join(format!("tests/fixtures/gpui_api/{trait_name}.txt")),
            format!(
                "# {trait_name} at {}\n# @generated by `cargo xtask gen-tables`; name/arity\n{}",
                revs.gpui,
                api.fixture(trait_name)
            ),
        ));
    }
    files.push((
        workspace.join("crates/gpui-stub/src/generated.rs"),
        stub(&methods, revs),
    ));
    files.push((
        workspace.join("demo/src/bin/generated_api_contract.rs"),
        demo_contract(&methods, theme_fields, revs),
    ));
    files.push((
        workspace.join("tests/common/generated_styled.rs"),
        mock_styled_defaults(&methods, revs, &workspace.join("tests/common/types.rs"))?,
    ));
    files.push((
        workspace.join("benches/support/generated_styled.rs"),
        mock_styled_defaults(&methods, revs, &workspace.join("benches/support/styled.rs"))?,
    ));
    Ok(Outputs { files })
}

const T_STYLED: u8 = 1;
const T_INTERACTIVE: u8 = 2;
const T_STATEFUL: u8 = 4;
const T_PARENT: u8 = 8;
const T_FLUENT: u8 = 16;

fn trait_bit(name: &str) -> u8 {
    match name {
        "Styled" => T_STYLED,
        "InteractiveElement" => T_INTERACTIVE,
        "StatefulInteractiveElement" => T_STATEFUL,
        "ParentElement" => T_PARENT,
        "FluentBuilder" => T_FLUENT,
        other => panic!("unknown trait {other}"),
    }
}

struct Merged {
    method: Method,
    traits: u8,
}

fn merged_methods(api: &GpuiApi) -> BTreeMap<String, Merged> {
    let mut out: BTreeMap<String, Merged> = BTreeMap::new();
    for (trait_name, methods) in &api.traits {
        let bit = trait_bit(trait_name);
        for m in methods {
            out.entry(m.name.clone())
                .and_modify(|e| {
                    e.traits |= bit;
                    e.method.arity = e.method.arity.max(m.arity);
                })
                .or_insert(Merged {
                    method: m.clone(),
                    traits: bit,
                });
        }
    }
    out
}

fn load_palette(path: &Path) -> Result<Vec<(String, String)>, String> {
    let text = std::fs::read_to_string(path)
        .map_err(|e| format!("failed to read {}: {e}", path.display()))?;
    let mut out = Vec::new();
    for line in text.lines().map(str::trim) {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (name, hex) = line
            .split_once(' ')
            .ok_or_else(|| format!("invalid palette line: {line}"))?;
        if hex.len() != 6 || u32::from_str_radix(hex, 16).is_err() {
            return Err(format!("invalid hex in palette line: {line}"));
        }
        out.push((name.to_owned(), hex.to_owned()));
    }
    Ok(out)
}

fn camel_case(snake: &str) -> String {
    let mut out = String::with_capacity(snake.len());
    let mut upper = false;
    for c in snake.chars() {
        if c == '_' {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn header(revs: &Revisions) -> String {
    format!(
        "// @generated by `cargo xtask gen-tables` from {} — DO NOT EDIT.\n\
         // Regenerate with: cargo xtask gen-tables [--gpui-src <source-root>]\n",
        revs.gpui
    )
}

fn core_tables(
    methods: &BTreeMap<String, Merged>,
    palette: &[(String, String)],
    revs: &Revisions,
) -> String {
    let mut s = header(revs);
    s.push_str(
        "//!\n//! Facts extracted from GPUI. The hand-written semantic layer lives in `tables.rs`.\n\n",
    );
    let _ = writeln!(
        s,
        "/// Published GPUI snapshot these tables were generated from.\npub const GPUI_SOURCE_REV: &str = \"{}\";",
        revs.gpui
    );
    let _ = writeln!(
        s,
        "/// Published gpui-component release verified together with [`GPUI_SOURCE_REV`].\npub const GPUI_COMPONENT_REV: &str = \"{}\";\n",
        revs.component
    );
    s.push_str(
        "pub const T_STYLED: u8 = 1;\npub const T_INTERACTIVE: u8 = 2;\npub const T_STATEFUL: u8 = 4;\npub const T_PARENT: u8 = 8;\npub const T_FLUENT: u8 = 16;\n\n",
    );
    s.push_str(
        "/// One builder method on a GPUI element trait.\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq)]\n\
         pub struct GpuiMethod {\n\
         \x20   pub name: &'static str,\n\
         \x20   /// Bit set of `T_*` trait flags.\n\
         \x20   pub traits: u8,\n\
         \x20   /// Number of arguments, excluding `self`.\n\
         \x20   pub arity: u8,\n\
         \x20   /// Family prefix for macro-generated presets/setters (`\"p\"`, `\"rounded_t\"`), else `\"\"`.\n\
         \x20   pub family_prefix: &'static str,\n\
         \x20   /// Family suffix for macro-generated presets (`\"4\"`, `\"md\"`), else `\"\"`.\n\
         \x20   pub family_suffix: &'static str,\n\
         \x20   /// `true` for `*_neg_*` presets.\n\
         \x20   pub negated: bool,\n\
         }\n\n",
    );

    s.push_str(
        "const fn m(\n    name: &'static str,\n    traits: u8,\n    arity: u8,\n    family_prefix: &'static str,\n    family_suffix: &'static str,\n    negated: bool,\n) -> GpuiMethod {\n    GpuiMethod { name, traits, arity, family_prefix, family_suffix, negated }\n}\n\n",
    );
    s.push_str("/// Every method, sorted by name.\n#[rustfmt::skip]\npub const GPUI_METHODS: &[GpuiMethod] = &[\n");
    for m in methods.values() {
        let (prefix, suffix, negated) = match &m.method.origin {
            Origin::Explicit => ("", "", false),
            Origin::FamilySetter { prefix, .. } => (prefix.as_str(), "", false),
            Origin::FamilyPreset {
                prefix,
                suffix,
                negated,
                ..
            } => (prefix.as_str(), suffix.as_str(), *negated),
        };
        let _ = writeln!(
            s,
            "    m(\"{}\", {}, {}, \"{prefix}\", \"{suffix}\", {negated}),",
            m.method.name, m.traits, m.method.arity
        );
    }
    s.push_str("];\n\n");

    s.push_str(
        "/// Looks up a GPUI method by its exact name (binary search over [`GPUI_METHODS`]).\npub fn lookup_gpui_method(name: &str) -> Option<&'static GpuiMethod> {\n    GPUI_METHODS\n        .binary_search_by(|m| m.name.cmp(name))\n        .ok()\n        .map(|index| &GPUI_METHODS[index])\n}\n\n",
    );

    s.push_str(
        "/// camelCase attribute → snake_case GPUI method for every method whose names differ.\npub fn lookup_gpui_camel_alias(name: &str) -> Option<&'static str> {\n    match name {\n",
    );
    let mut aliases = BTreeMap::new();
    for name in methods.keys() {
        let camel = camel_case(name);
        if camel != *name && !methods.contains_key(&camel) {
            aliases.insert(camel, name.clone());
        }
    }
    for (camel, snake) in &aliases {
        let _ = writeln!(s, "        \"{camel}\" => Some(\"{snake}\"),");
    }
    s.push_str("        _ => None,\n    }\n}\n\n");

    s.push_str(
        "/// Tailwind palette lookup (`family_shade`, `black`, `white`) from `xtask/data/tailwind-palette.txt`.\npub fn lookup_color(name: &str) -> Option<u32> {\n    match name {\n",
    );
    for (name, hex) in palette {
        let _ = writeln!(s, "        \"{name}\" => Some(0x{hex}),");
    }
    s.push_str("        _ => None,\n    }\n}\n\n");

    let mut families: Vec<&str> = Vec::new();
    let mut shades: Vec<&str> = Vec::new();
    for (name, _) in palette {
        if let Some((family, shade)) = name.rsplit_once('_') {
            if !families.contains(&family) {
                families.push(family);
            }
            if !shades.contains(&shade) {
                shades.push(shade);
            }
        }
    }
    let _ = writeln!(
        s,
        "/// Tailwind color families ({}).\npub const COLOR_FAMILIES: &[&str] = &[{}];\n",
        families.len(),
        families
            .iter()
            .map(|f| format!("\"{f}\""))
            .collect::<Vec<_>>()
            .join(", ")
    );
    let _ = writeln!(
        s,
        "/// Tailwind color shades ({}).\npub const COLOR_SHADES: &[&str] = &[{}];",
        shades.len(),
        shades
            .iter()
            .map(|f| format!("\"{f}\""))
            .collect::<Vec<_>>()
            .join(", ")
    );
    s
}

/// Methods the stub implements by hand because their closures need concrete types.
const STUB_MANUAL: &[&str] = &[
    "style",
    "text_style",
    "interactivity",
    "id",
    "hover",
    "focus",
    "focus_visible",
    "in_focus",
    "active",
    "group_hover",
    "group_active",
    "on_click",
    "on_hover",
    "on_mouse_down",
    "on_mouse_up",
    "on_key_down",
    "tooltip",
    "child",
    "children",
    "extend",
    "map",
    "when",
    "when_else",
    "when_some",
    "when_none",
];

fn stub(methods: &BTreeMap<String, Merged>, revs: &Revisions) -> String {
    let mut s = header(revs);
    s.push_str("//!\n//! Generic stand-ins for every GPUI builder method; see `lib.rs` for typed ones.\n\n");
    s.push_str("use crate::*;\n\n");

    let groups: [(&str, u8, &str); 3] = [
        ("GeneratedStyled", T_STYLED, "Sized"),
        ("GeneratedInteractive", T_INTERACTIVE, "Sized"),
        ("GeneratedStateful", T_STATEFUL, "Sized"),
    ];
    for (trait_name, bit, bound) in groups {
        let _ = writeln!(s, "pub trait {trait_name}: {bound} {{");
        for m in methods.values() {
            if m.traits & bit == 0 || STUB_MANUAL.contains(&m.method.name.as_str()) {
                continue;
            }
            // A method declared on several traits is only emitted on the first one.
            let first_bit = [T_STYLED, T_INTERACTIVE, T_STATEFUL]
                .into_iter()
                .find(|b| m.traits & b != 0);
            if first_bit != Some(bit) {
                continue;
            }
            let name = &m.method.name;
            match m.method.arity {
                0 => {
                    let _ = writeln!(s, "    fn {name}(self) -> Self {{ self }}");
                }
                n => {
                    let generics: Vec<String> = (0..n).map(|i| format!("A{i}")).collect();
                    let params: Vec<String> = (0..n).map(|i| format!("_: A{i}")).collect();
                    let _ = writeln!(
                        s,
                        "    fn {name}<{}>(self, {}) -> Self {{ self }}",
                        generics.join(", "),
                        params.join(", ")
                    );
                }
            }
        }
        s.push_str("}\n\n");
    }
    s.push_str("impl GeneratedStyled for Div {}\nimpl GeneratedStyled for Stateful<Div> {}\nimpl GeneratedStyled for StyleRefinement {}\nimpl GeneratedStyled for Svg {}\nimpl GeneratedStyled for Img {}\nimpl<T> GeneratedStyled for Canvas<T> {}\n");
    s.push_str("impl GeneratedInteractive for Div {}\nimpl GeneratedInteractive for Stateful<Div> {}\nimpl GeneratedInteractive for Svg {}\nimpl GeneratedInteractive for Img {}\n");
    s.push_str("impl GeneratedStateful for Stateful<Div> {}\n");
    s
}

fn demo_contract(
    methods: &BTreeMap<String, Merged>,
    theme_fields: &[String],
    revs: &Revisions,
) -> String {
    let mut s = header(revs);
    s.push_str(
        "//! Compile-only contract: every zero-argument GPUI method that `gpui-rsx` maps classes to\n\
         //! must exist with that exact name. Built by `cargo check --bins` in CI.\n\n\
         use gpui::prelude::*;\nuse gpui::*;\n\n\
         #[allow(dead_code)]\nfn styled_contract(mut el: Div) -> Div {",
    );
    // `style`/`text_style` return references; `debug*` only exist with debug_assertions.
    let skip = ["debug", "debug_below", "style", "text_style"];
    for m in methods.values() {
        if m.traits & T_STYLED != 0
            && m.method.arity == 0
            && !skip.contains(&m.method.name.as_str())
        {
            let _ = write!(s, "\n    el = el.{}();", m.method.name);
        }
    }
    s.push_str("\n    el\n}\n\n#[allow(dead_code)]\nfn stateful_contract(mut el: Stateful<Div>) -> Stateful<Div> {");
    for m in methods.values() {
        if m.traits & T_STATEFUL != 0 && m.method.arity == 0 {
            let _ = write!(s, "\n    el = el.{}();", m.method.name);
        }
    }
    s.push_str("\n    el\n}\n\n#[allow(dead_code)]\nfn theme_contract(cx: &App) {\n    use gpui::component::ActiveTheme as _;\n");
    for field in theme_fields {
        let _ = writeln!(s, "    let _: Hsla = cx.theme().colors.{field};");
    }
    s.push_str("}\n\nfn main() {\n    let _ = styled_contract;\n    let _ = stateful_contract;\n    let _ = theme_contract;\n}\n");
    s
}

/// Default no-op impls for every zero-argument `Styled` method that the hand-written test
/// mock (`tests/common/types.rs`) does not declare itself.
fn mock_styled_defaults(
    methods: &BTreeMap<String, Merged>,
    revs: &Revisions,
    mock: &Path,
) -> Result<String, String> {
    let source = std::fs::read_to_string(mock)
        .map_err(|e| format!("failed to read {}: {e}", mock.display()))?;
    let file =
        syn::parse_file(&source).map_err(|e| format!("failed to parse {}: {e}", mock.display()))?;
    let declared: Vec<String> = file
        .items
        .iter()
        .find_map(|item| match item {
            syn::Item::Trait(t) if t.ident == "Styled" => Some(
                t.items
                    .iter()
                    .filter_map(|i| match i {
                        syn::TraitItem::Fn(f) => Some(f.sig.ident.to_string()),
                        _ => None,
                    })
                    .collect(),
            ),
            _ => None,
        })
        .ok_or("trait Styled not found in tests/common/types.rs")?;

    let mut s = header(revs);
    s.push_str("\nmacro_rules! generated_styled_defaults {\n    () => {\n");
    for m in methods.values() {
        if m.traits & T_STYLED != 0 && m.method.arity == 0 && !declared.contains(&m.method.name) {
            let _ = writeln!(s, "        fn {}(self) -> Self {{ self }}", m.method.name);
        }
    }
    s.push_str("    };\n}\n");
    Ok(s)
}
